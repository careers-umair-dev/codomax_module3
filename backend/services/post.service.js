const postRepository = require('../repositories/post.repository');
const ApiError = require('../utils/ApiError');
const { normalizeImage } = require('./image.service');

const EXCERPT_LENGTH = 140;

function makeExcerpt(content) {
  const clean = content.replace(/\s+/g, ' ').trim();
  return clean.length > EXCERPT_LENGTH ? `${clean.slice(0, EXCERPT_LENGTH).trim()}…` : clean;
}

async function listPosts({ search, category, authorId } = {}) {
  return postRepository.findAll({ search, category, authorId });
}

async function getPost(id) {
  const post = await postRepository.findById(id);
  if (!post) throw ApiError.notFound('Post not found.');
  return post;
}

/** `author` comes from the verified JWT, never from the request body. */
async function createPost({ title, category, content, image }, author) {
  // _id, createdAt and updatedAt are generated by MongoDB/Mongoose.
  return postRepository.create({
    title,
    category,
    content,
    excerpt: makeExcerpt(content),
    image: normalizeImage(image),
    authorId: author.id,
    authorName: author.name,
  });
}

/** Loads the post and enforces ownership: 404 if missing, 403 if not the author. */
async function getOwnedPost(id, user, action) {
  const post = await getPost(id);
  if (post.authorId !== user.id) {
    throw ApiError.forbidden(`You can only ${action} your own posts.`);
  }
  return post;
}

async function updatePost(id, { title, category, content, image }, user) {
  const existing = await getOwnedPost(id, user, 'edit');

  const changes = {
    title,
    category,
    content,
    excerpt: makeExcerpt(content),
    // undefined = keep current cover, '' = remove it, anything else = replace it
    image: image === undefined ? existing.image : normalizeImage(image),
  };

  const updated = await postRepository.update(id, changes);
  if (!updated) throw ApiError.notFound('Post not found.'); // deleted mid-request
  return updated;
}

async function deletePost(id, user) {
  await getOwnedPost(id, user, 'delete');
  const removed = await postRepository.remove(id);
  if (!removed) throw ApiError.notFound('Post not found.');
}

module.exports = { listPosts, getPost, createPost, updatePost, deletePost };
